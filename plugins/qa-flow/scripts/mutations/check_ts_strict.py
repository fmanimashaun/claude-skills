"""Mutation guard: check_ts_strict. Run by scripts/mutation_check.py (#1447)."""
from mutation_types import Guard, Mutation  # noqa: F401

# Each mutation restores a way the gate would report a TypeScript suite as strict when it is not: a rule
# that stops firing, a carve-out that swallows a finding, or a scanner that blanks real code (the first
# downstream run found one: a template literal's `${...}` put the string blanker out of phase).
GUARD = Guard(
    name="check_ts_strict",
    subject="scripts/check_ts_strict.py",
    selftest="scripts/check_ts_strict.py",
    mutations=(
        Mutation("a non-strict tsconfig stops being a finding",
                 "        if not strict:\n", "        if False:\n",
                 "a tsconfig without strict is caught"),
        Mutation("strict: false is read as strict",
                 '        return opts["strict"] is True', '        return True',
                 "strict: false is caught"),
        Mutation("an inherited strict is no longer followed through extends",
                 "            return is_strict(target, depth + 1)", "            return False",
                 "strict inherited through a relative extends counts"),
        Mutation("a missing typecheck step stops being a finding",
                 "    if typecheck_step(root) is None:\n", "    if False:\n",
                 "no typecheck step is caught"),
        Mutation("a tsc mentioned in a CI comment counts as a step",
                 "            if not COMMENT_LINE.match(line) and TSC.search(line):",
                 "            if TSC.search(line):",
                 "a tsc mentioned only in a CI COMMENT is not a step"),
        Mutation("package.json scripts are no longer read",
                 "            if isinstance(cmd, str) and TSC.search(cmd):",
                 "            if False:",
                 "a package.json typecheck script counts"),
        Mutation("explicit any stops being a finding",
                 "        if not ANY.search(line):\n            continue\n",
                 "        continue\n",
                 "explicit any is caught"),
        Mutation("`as any` is no longer matched",
                 r'ANY = re.compile(r"(?::\s*any\b|\bas\s+any\b|<any>|\bany\s*\[\s*\]|Array<\s*any\s*>)")',
                 r'ANY = re.compile(r"(?::\s*any\b|<any>|\bany\s*\[\s*\]|Array<\s*any\s*>)")',
                 "explicit any is caught: f(key as any);"),
        Mutation("comments are no longer blanked, so a described any is a finding",
                 "    for n, line in enumerate(_blank(source).split(\"\\n\")):",
                 "    for n, line in enumerate(source.split(\"\\n\")):",
                 "`any` in a comment is not code"),
        Mutation("a template's ${...} is blanked as text, hiding an any inside it",
                 "                i = scan_code(i + 2, closing=\"}\")",
                 "                i += 2",
                 "an `any` inside a template's ${...} expression is code"),
        Mutation("a '...' string may run past its line again",
                 "                while j < n and text[j] != c and text[j] != \"\\n\":",
                 "                while j < n and text[j] != c:",
                 "a stray quote in a '...' string cannot run past its line"),
        Mutation("an allow-any declaration no longer needs a reason",
                 r'ALLOW = re.compile(r"ts-strict:[ \t]*allow-any[ \t]*--[ \t]*\w")',
                 r'ALLOW = re.compile(r"ts-strict:[ \t]*allow-any")',
                 "a declaration with no reason is not one"),
        Mutation("no TypeScript reads as clean instead of not applicable",
                 "    if not ts:\n        return None\n", "    if not ts:\n        return [], 0\n",
                 "no TypeScript under qa/ is NOT APPLICABLE, not a pass"),
    ),
)
